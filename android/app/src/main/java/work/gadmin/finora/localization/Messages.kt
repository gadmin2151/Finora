    fun render(language: AppLanguage, vararg arguments: Any?): String {
        val template = if (language == AppLanguage.RUSSIAN) russian else english
        return placeholder.replace(template) { match ->
            val index = match.groupValues[1].toInt() - 1
            require(index in arguments.indices) { "Missing localization argument: $name" }
            arguments[index]?.toString().orEmpty()
        }
    }

    companion object {
        private val placeholder = Regex("%([1-9][0-9]*)\\\$s")
    }
}

/** Reading snapshot state makes Compose call sites update without recreating their forms. */
fun tr(message: Message, vararg arguments: Any?): String =
    message.render(LanguageRuntime.language, *arguments)
